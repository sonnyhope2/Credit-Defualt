"""Step 4: explain the models: SHAP for LightGBM, odds ratios for logistic regression, and
partial dependence curves that put all four models on the same log-odds scale.

Run:  python src/explain.py
Output: reports/explain.md, reports/lr_coefficients.csv, reports/figures/*.png
"""
import joblib
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from config import FIG_DIR, MODEL_LABELS, MODEL_NAMES, MODELS_DIR, REPORTS_DIR, SEED, TEST_YEARS
from evaluate import COLORS, logit, md_table, years_label
from features import BINARY, FEATURES, MONOTONE, NUMERIC, load_modelling_data

try:
    import shap  # only needed for the beeswarm plot
except ImportError:
    shap = None

N_SHAP = 20_000   # test loans used for SHAP
N_PD = 3_000      # test loans used for partial dependence
PD_FEATURES = ["credit_score", "ltv", "dti", "rate_spread"]


def lgbm_shap(pipe, X):
    """Exact TreeSHAP values computed by LightGBM itself, in log-odds units."""
    Xc = pipe.named_steps["cast"].transform(X)
    model = pipe.named_steps["model"]
    contrib = model.predict(Xc, pred_contrib=True)  # last column is the baseline (expected value)
    # Sanity check: per loan, baseline + contributions must equal the model's log-odds output
    assert np.allclose(contrib.sum(axis=1), model.predict(Xc, raw_score=True), atol=1e-6)
    return pd.DataFrame(contrib[:, :-1], columns=FEATURES, index=X.index), contrib[:, -1]


def partial_dependence(pipe, X, feature, grid):
    """Average log-odds when `feature` is set to each grid value for every loan in X."""
    curve = []
    for v in grid:
        Xv = X.copy()
        Xv[feature] = v
        curve.append(logit(pipe.predict_proba(Xv)[:, 1]).mean())
    return np.array(curve)


def lr_coefficients(pipe):
    names = [n.split("__", 1)[1] for n in pipe.named_steps["pre"].get_feature_names_out()]
    coef = pipe.named_steps["model"].coef_[0]
    table = pd.DataFrame({"coefficient": coef, "odds_ratio": np.exp(coef)}, index=names)
    table.index.name = "term"
    return table.reindex(table["coefficient"].abs().sort_values(ascending=False).index)


def main():
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    models = {m: joblib.load(MODELS_DIR / f"{m}.joblib") for m in MODEL_NAMES}
    df = load_modelling_data()
    test = df[df["split"] == "test"]
    sample = test.sample(min(N_SHAP, len(test)), random_state=SEED)
    X = sample[FEATURES]
    out = [f"# Explanations\n\nGenerated by `src/explain.py` on out-of-time test loans ({years_label(TEST_YEARS)})."]

    # 1. SHAP for both LightGBMs
    shap_vals = {m: lgbm_shap(models[m], X)[0] for m in ["lgbm", "lgbm_monotone"]}
    print("SHAP additivity check passed (contributions sum to the model output)")
    importance = pd.DataFrame({MODEL_LABELS[m]: v.abs().mean() for m, v in shap_vals.items()})
    importance = importance.sort_values(MODEL_LABELS["lgbm"], ascending=False)
    importance.index.name = "feature"

    fig, ax = plt.subplots(figsize=(8, 6))
    ypos = np.arange(len(importance))
    for i, (m, col) in enumerate(zip(["lgbm", "lgbm_monotone"], importance.columns)):
        ax.barh(ypos + (i - 0.5) * 0.4, importance[col], height=0.4, color=COLORS[m], label=col)
    ax.set_yticks(ypos, importance.index)
    ax.invert_yaxis()
    ax.set(xlabel="Mean |SHAP value| (log-odds)", title="Global feature importance (LightGBM)")
    ax.legend()
    fig.tight_layout()
    fig.savefig(FIG_DIR / "shap_importance.png", dpi=150)
    plt.close(fig)

    if shap is not None:
        ordered = NUMERIC + BINARY  # features with a natural order, so colour means high/low
        shap.summary_plot(shap_vals["lgbm"][ordered].to_numpy(), X[ordered].astype(float),
                          feature_names=ordered, show=False, max_display=len(ordered))
        plt.title("SHAP values, LightGBM (red = high feature value)")
        plt.tight_layout()
        plt.savefig(FIG_DIR / "shap_beeswarm.png", dpi=150)
        plt.close("all")
    else:
        print("shap is not installed: skipping the beeswarm plot (pip install shap)")

    out += ["## Global importance (mean |SHAP|, log-odds)", md_table(importance, {c: "{:.3f}" for c in importance})]

    # 2. Partial dependence: every model's learned effect on the same log-odds scale
    pd_sample = X.sample(min(N_PD, len(X)), random_state=SEED)
    fig, axes = plt.subplots(2, 2, figsize=(11, 8))
    checks = []
    for ax, f in zip(axes.ravel(), PD_FEATURES):
        values = pd_sample[f].dropna()
        grid = np.unique(np.quantile(values, np.linspace(0.02, 0.98, 25)))
        centre = values.median()
        hist = ax.twinx()
        hist.hist(values, bins=40, color="lightgrey", alpha=0.6)
        hist.set_yticks([])
        ax.set_zorder(hist.get_zorder() + 1)
        ax.patch.set_visible(False)
        for m in MODEL_NAMES:
            curve = partial_dependence(models[m], pd_sample, f, grid)
            curve = curve - np.interp(centre, grid, curve)  # 0 = a loan at the median
            ax.plot(grid, curve, color=COLORS[m], lw=2, label=MODEL_LABELS[m])
            if m == "lgbm_monotone" and f in MONOTONE:
                ok = bool(np.all(np.diff(curve) * MONOTONE[f] >= -1e-9))
                checks.append(f"{f}: {'monotone as required' if ok else 'NOT MONOTONE - check constraints'}")
        ax.axhline(0, color="k", lw=0.5)
        ax.set(xlabel=f, ylabel="Change in log-odds vs median loan")
    axes[0, 0].legend(fontsize=8)
    fig.suptitle("Partial dependence: what each model learned (grey = distribution of the feature)")
    fig.tight_layout()
    fig.savefig(FIG_DIR / "partial_dependence.png", dpi=150)
    plt.close(fig)
    print("Monotone constraint check:\n  " + "\n  ".join(checks))

    # 3. Local explanation: one high-risk loan that did default
    defaulted = sample[sample["default"] == 1]
    if len(defaulted):
        p_lgbm = models["lgbm"].predict_proba(defaulted[FEATURES])[:, 1]
        pick = defaulted.index[np.argsort(p_lgbm)[int(0.9 * (len(p_lgbm) - 1))]]
        row = shap_vals["lgbm"].loc[pick]
        top = row.reindex(row.abs().sort_values(ascending=False).index)[:10][::-1]

        def show(f):
            v = sample.loc[pick, f]
            return f"{f} = {v:.4g}" if isinstance(v, (int, float, np.number)) else f"{f} = {v}"

        p_one = {m: models[m].predict_proba(sample.loc[[pick], FEATURES])[0, 1] for m in MODEL_NAMES}
        fig, ax = plt.subplots(figsize=(8, 5))
        ax.barh([show(f) for f in top.index], top.values,
                color=["#d62728" if v > 0 else "#1f77b4" for v in top.values])
        ax.axvline(0, color="k", lw=0.5)
        ax.set(xlabel="SHAP value (log-odds): red raises risk, blue lowers it",
               title=f"Why LightGBM rated this loan risky: PD {p_one['lgbm']:.1%} "
                     f"(logistic regression: {p_one['lr_linear']:.1%})")
        fig.tight_layout()
        fig.savefig(FIG_DIR / "local_explanation.png", dpi=150)
        plt.close(fig)

    # 4. Logistic regression coefficients (numeric features are per 1 standard deviation)
    coefs = lr_coefficients(models["lr_linear"])
    coefs.to_csv(REPORTS_DIR / "lr_coefficients.csv")
    out += ["## Logistic regression: largest coefficients",
            "Numeric features are standardised, so their odds ratio is per one standard deviation.",
            md_table(coefs.head(15), {"coefficient": "{:+.3f}", "odds_ratio": "{:.2f}"})]

    (REPORTS_DIR / "explain.md").write_text("\n\n".join(out) + "\n", encoding="utf-8")
    print("\nLightGBM importance (mean |SHAP|):\n", importance.round(3).to_string())
    print("\nTop logistic regression terms:\n", coefs.head(15).round(3).to_string())
    print(f"\nWrote {REPORTS_DIR / 'explain.md'} and figures to {FIG_DIR}")


if __name__ == "__main__":
    main()
